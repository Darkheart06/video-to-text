BUILTIN = {p.key: p for p in (MEETING, ESTIMATE, NOTE, INTERVIEW)}
DEFAULT = MEETING.key

CUSTOM_KEY = "custom"
CUSTOM_TITLE = "Свои правила"
CUSTOM_HINT = ("Напишите словами, что нужно получить, — и задайте шаблон "
               "заголовками ##. Приложение само разложит ответ по вкладкам.")

CUSTOM_EXAMPLE = """## Кратко
- (о чём запись)

## Таблица
| Пункт | Количество | Ставка | Стоимость |
|---|---|---|---|

## Прочее
- (всё остальное)"""


def _sections_from_template(template: str) -> list[tuple[str, str]]:
    """Достаёт заголовки ## из пользовательского шаблона, чтобы разложить
    ответ модели по вкладкам без всякой настройки."""
    import re

    found: list[tuple[str, str]] = []
    for i, line in enumerate(template.split("\n")):
        m = re.match(r"^\s*##\s+(?!#)(.+?)\s*$", line)
        if m:
            title = m.group(1).strip()
            found.append((f"s{i}", title))
    return found or [("summary", "Кратко")]


def build_custom(rules: str, template: str) -> Preset:
    template = (template or "").strip() or CUSTOM_EXAMPLE
    sections = _sections_from_template(template)
    return Preset(
        key=CUSTOM_KEY, title=CUSTOM_TITLE, hint=CUSTOM_HINT,
        rules=(rules or "").strip(),
        template=template,
        what="документ",
        sections=sections,
        # Пересчитываем таблицы во всех разделах: пользователь мог попросить
        # смету своими словами, и считать всё равно должны мы, а не модель.
        tables=[key for key, _ in sections],
    )


def resolve(settings) -> Preset:
    key = settings.get("preset", DEFAULT)
    if key == CUSTOM_KEY:
        return build_custom(settings.get("custom_rules", ""),
                            settings.get("custom_template", ""))
    return BUILTIN.get(key, MEETING)


def tabs_for(keys: list[str]) -> list[tuple[str, str]]:
    """Подбирает подписи вкладок по ключам разделов.

    Нужно для старых записей из архива: там сохранены только ключи, а какой
    профиль их сделал — неизвестно. Берём профиль, который совпал сильнее всех.
    """
    keys = [k for k in keys if k]
    best, score = None, -1
    for preset in BUILTIN.values():
        hit = len({k for k, _ in preset.sections} & set(keys))
        if hit > score:
            best, score = preset, hit
    titles = dict(best.sections) if best else {}
    return [(k, titles.get(k) or k.replace("_", " ").capitalize()) for k in keys]


def catalogue() -> list[dict]:
    """Список профилей для интерфейса."""
    items = [{"key": p.key, "title": p.title, "hint": p.hint} for p in BUILTIN.values()]
    items.append({"key": CUSTOM_KEY, "title": CUSTOM_TITLE, "hint": CUSTOM_HINT})
    return items
